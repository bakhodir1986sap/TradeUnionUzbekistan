
CREATE view dbo.VKaznaBankFileD as
select K.OPERDAY , K.KLSDOX , K.COACC , SUM(K.SUMPAY) as  SUMPAY
from KasabaKIAT_N1.dbo.KaznaBankFile K
GROUP BY K.OPERDAY , K.KLSDOX , K.COACC;

CREATE view dbo.VKaznaBankFileM as
select DATEPART(YEAR , K.OPERDAY) as OPERYEAR , DATEPART(MONTH , K.OPERDAY) as OPERDAY , K.KLSDOX , K.COACC , SUM(K.SUMPAY)  as  SUMPAY
from KasabaKIAT_N1.dbo.KaznaBankFile K
GROUP BY DATEPART(YEAR , K.OPERDAY) , DATEPART(MONTH , K.OPERDAY) , K.KLSDOX , K.COACC;

CREATE view dbo.VKaznaBankFileQ as
select DATEPART(YEAR , K.OPERDAY) as OPERYEAR , DATEPART(q , K.OPERDAY) as OPERDAY , K.KLSDOX , K.COACC , SUM(K.SUMPAY)  as  SUMPAY
from KasabaKIAT_N1.dbo.KaznaBankFile K
GROUP BY DATEPART(YEAR , K.OPERDAY) , DATEPART(q , K.OPERDAY) , K.KLSDOX , K.COACC;

CREATE view dbo.VKaznaBankFileY as
select DATEPART(YEAR , K.OPERDAY) as OPERDAY , K.KLSDOX , K.COACC , SUM(K.SUMPAY)  as  SUMPAY
from KasabaKIAT_N1.dbo.KaznaBankFile K
GROUP BY DATEPART(YEAR , K.OPERDAY) , K.KLSDOX , K.COACC;